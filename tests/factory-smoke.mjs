import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const htmlPath = resolve('factory/index.html');
const html = await readFile(htmlPath, 'utf8');
const server = createServer((req, res) => {
  res.writeHead(200, { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' });
  res.end(html);
});
await new Promise(resolveListen => server.listen(4173, '127.0.0.1', resolveListen));
const browser = await chromium.launch({ headless: true });
const errors = [];
const results = [];
const assert = (condition, message) => { if (!condition) throw new Error(message); results.push('PASS: ' + message); };
const temp = await mkdtemp(join(tmpdir(), 'factory-smoke-'));
let context;
try {
  context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await page.goto('http://127.0.0.1:4173/', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(150);
  assert(await page.title() === 'Castel App Factory', 'desktop page loads');
  assert(await page.locator('#v-create').evaluate(e => e.classList.contains('on')), 'Create view initializes');
  await page.getByRole('button', { name: 'Projects' }).click();
  assert(await page.locator('#v-projects').evaluate(e => e.classList.contains('on')), 'Projects navigation responds');
  await page.getByRole('button', { name: 'Settings' }).click();
  assert(await page.locator('#v-settings').evaluate(e => e.classList.contains('on')), 'Settings navigation responds');
  await page.getByRole('button', { name: 'Create' }).click();
  await page.locator('#newProj').click();
  await page.locator('#srcFile').setInputFiles({ name: 'smoke-test.html', mimeType: 'text/html', buffer: Buffer.from('<!doctype html><html><body><h1>Factory Smoke Test</h1></body></html>') });
  await page.locator('[data-k="name"]').fill('Factory Smoke Test');
  await page.locator('[data-k="pkg"]').fill('com.castel.smoketest');
  await page.locator('[data-k="vname"]').fill('1.0.0');
  await page.locator('[data-k="vcode"]').fill('1');
  await page.waitForTimeout(150);
  assert((await page.locator('#dropT').textContent()).includes('smoke-test.html'), 'HTML source upload and binding work');
  await page.getByRole('button', { name: 'Projects' }).click();
  assert(await page.locator('#plist').getByText('Factory Smoke Test').count() === 1, 'project auto-saves and renders in Projects');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#exp').click();
  const download = await downloadPromise;
  const backupPath = join(temp, 'backup.json');
  await download.saveAs(backupPath);
  const backup = JSON.parse(await readFile(backupPath, 'utf8'));
  assert(Array.isArray(backup) && backup.some(p => p.name === 'Factory Smoke Test' && p.html.includes('Factory Smoke Test')), 'Export produces a valid backup containing project source');
  await page.evaluate(() => { localStorage.removeItem('castel.projects'); });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Projects' }).click();
  await page.locator('#imp').setInputFiles(backupPath);
  await page.waitForFunction(() => document.querySelector('#plist')?.textContent.includes('Factory Smoke Test'));
  assert(await page.locator('#plist').getByText('Factory Smoke Test').count() === 1, 'Import restores project and renders it');
  await page.locator('#plist').getByRole('button', { name: 'Open' }).click();
  assert(await page.locator('[data-k="name"]').inputValue() === 'Factory Smoke Test', 'Open loads selected project into editor');
  await page.getByRole('button', { name: 'Projects' }).click();
  await page.locator('#plist').getByRole('button', { name: 'Duplicate' }).click();
  await page.waitForFunction(() => document.querySelector('#plist')?.textContent.includes('Factory Smoke Test copy'));
  assert(await page.locator('#plist').getByText('Factory Smoke Test copy').count() === 1, 'Duplicate creates a separate project');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#plist').getByRole('button', { name: 'Delete' }).last().click();
  await page.waitForTimeout(100);
  if (errors.length) throw new Error('Browser console errors:\n' + errors.join('\n'));
  results.push('PASS: no uncaught browser or console errors');
  console.log(results.join('\n'));
} finally {
  if (context) await context.close();
  await browser.close();
  await new Promise(resolveClose => server.close(resolveClose));
  await rm(temp, { recursive: true, force: true });
}
